# Builds dist\KakaoAdHide-windows.exe (the release asset; it installs itself as KakaoAdHide.exe)
# with the C# compiler that ships with Windows (.NET Framework 4.x).
# Nothing to install. Usage:
#   powershell -ExecutionPolicy Bypass -File windows\build.ps1                 # version from VERSION
#   powershell -ExecutionPolicy Bypass -File windows\build.ps1 -Version 1.2.0  # override (the release workflow checks it matches the tag)
#   -Define TEST_FEED -Out <path>                                      # test builds (local update feed, see src/Updater.cs)

param(
  [string] $Version,
  [string] $Define,
  [string] $Out
)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot                     # windows/ (sources)
$repo = Split-Path $PSScriptRoot -Parent  # repository root (VERSION, dist)
$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) { $csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v4.0.30319\csc.exe' }
if (-not (Test-Path $csc)) { throw "csc.exe (.NET Framework 4.x) not found" }

if (-not $Version) { $Version = (Get-Content (Join-Path $repo 'VERSION') -Raw).Trim() }
if ($Version -notmatch '^\d+\.\d+\.\d+$') { throw "version must look like 1.2.3 (got '$Version')" }

$dist = Join-Path $repo 'dist'
New-Item -ItemType Directory -Force $dist | Out-Null
if (-not $Out) { $Out = Join-Path $dist 'KakaoAdHide-windows.exe' }
New-Item -ItemType Directory -Force (Split-Path $Out -Parent) | Out-Null

# assembly attributes + BuildInfo.Version, generated from the version
$obj = Join-Path $root 'obj'
New-Item -ItemType Directory -Force $obj | Out-Null
$buildInfo = Join-Path $obj 'BuildInfo.cs'
@"
// generated by build.ps1 - do not edit
using System.Reflection;
[assembly: AssemblyTitle("KakaoAdHide")]
[assembly: AssemblyProduct("KakaoAdHide")]
[assembly: AssemblyDescription("Hides the ad banner of KakaoTalk for Windows")]
[assembly: AssemblyCopyright("Copyright (c) 2026 pandemoniummm, MIT License")]
[assembly: AssemblyVersion("$Version.0")]
[assembly: AssemblyFileVersion("$Version.0")]
[assembly: AssemblyInformationalVersion("$Version")]
static class BuildInfo { public const string Version = "$Version"; }
"@ | Set-Content -Path $buildInfo -Encoding UTF8

$src = @(Get-ChildItem (Join-Path $root 'src') -Filter *.cs | ForEach-Object { $_.FullName }) + $buildInfo

$cscArgs = @('/nologo', '/target:winexe', '/platform:anycpu', '/optimize+', '/codepage:65001',
             '/reference:System.Windows.Forms.dll', '/reference:System.Drawing.dll', '/reference:System.Runtime.Serialization.dll',
             "/out:$Out")
if ($Define) { $cscArgs += "/define:$Define" }
$ico = Join-Path $root 'assets\app.ico'
if (Test-Path $ico) { $cscArgs += "/win32icon:$ico" }

& $csc @cscArgs @src
if ($LASTEXITCODE -ne 0) { throw "build failed ($LASTEXITCODE)" }

if (-not $Define) {
  $hash = (Get-FileHash $Out -Algorithm SHA256).Hash.ToLower()
  "$hash  $(Split-Path $Out -Leaf)" | Set-Content -Path (Join-Path (Split-Path $Out -Parent) 'SHA256SUMS.txt') -Encoding ascii
  Write-Host "sha256 $hash"
}
Write-Host "built $Out (version $Version)"
